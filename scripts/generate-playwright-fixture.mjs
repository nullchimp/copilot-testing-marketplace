import { spawnSync } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import assert from "node:assert/strict";

const root = fileURLToPath(new URL("../", import.meta.url));
const temp = await mkdtemp(join(tmpdir(), "test-lab-producer-"));
try {
  const output = join(temp, "junit.xml");
  const result = spawnSync(process.execPath, [
    join(root, "node_modules/@playwright/test/cli.js"), "test", "--config", join(root, "tests/producers/playwright.config.mjs"),
  ], {
    cwd: root, encoding: "utf8",
    env: { ...process.env, FORCE_COLOR: "0", PLAYWRIGHT_JUNIT_OUTPUT_FILE: output, TEST_LAB_PRODUCER_OUTPUT: join(temp, "results") },
  });
  assert.equal(result.status, 1, `The original fixture must include a failing test. ${result.error ?? result.stderr}`);
  const raw = await readFile(output, "utf8");
  assert.match(raw, /tests="5"/);
  const sanitized = raw.replaceAll(root.replace(/\/$/, ""), "/fixture")
    .replace(/timestamp="[^"]*"/g, 'timestamp="2026-01-01T00:00:00.000Z"')
    .replace(/time="[^"]*"/g, 'time="0.001"')
    .replace(/^\s*Error Context: .+$/gm, "    Error Context: /fixture/artifacts/error-context.md")
    .replace(/\x1b\[[0-9;]*m/g, "");
  assert.doesNotMatch(sanitized, /\/(?:Users|home|private|var\/folders)\//, "Public fixture must not contain machine-specific paths.");
  const header = "<!-- Generated by @playwright/test 1.63.0 from original producer cases. Paths, timestamps and timings normalized; outcomes unchanged. -->\n";
  await mkdir(new URL("../tests/fixtures/", import.meta.url), { recursive: true });
  await writeFile(new URL("../tests/fixtures/playwright-junit.xml", import.meta.url), header + sanitized);
  console.info("Generated actual Playwright JUnit fixture: 2 passed, 1 failed, 2 skipped; no browser used.");
} finally {
  await rm(temp, { recursive: true, force: true });
}
